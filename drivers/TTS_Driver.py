def ort_gpu_available():
    """ function to check if ONNX GPU is installed so you can run with 
    cuda acceleration"""
    try:
        import onnxruntime as ort
        return "CUDAExecutionProvider" in ort.get_available_providers()
    except ImportError:
        return False

def is_cuda_usable(model_path: str):
    """checks if ONNX GPU is installed and useable so you can use cuda 
    acceleration"""
    try:
        import onnxruntime as ort
        sess = ort.InferenceSession(
            model_path,
            providers=["CUDAExecutionProvider", "CPUExecutionProvider"]
        )
        # If it chose CUDA, GPU is actually active
        return sess.get_providers()[0] == "CUDAExecutionProvider"
    except Exception as e:
        print("CUDA unusable:", e)
        return False
    
