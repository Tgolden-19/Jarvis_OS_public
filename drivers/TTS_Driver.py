def phoneme_labelled(word_phon_map, alphabet='cmu-arpabet'):
    """takes in the exact word to phonetic mapping generated by the to_arpabet
      function in the chat driver and prepares it into a list that can be 
      injected into an elevenlabs prompt by adding all phonetic labels"""
    tags = []
    for mapping in word_phon_map:
        word = mapping[0]
        phon = mapping[1]
        tags += f'<phoneme alphabet="{alphabet}" ph="{phon}">\n {word}\n <\phoneme>'
    return tags

def assemble_from_tags(tags):
    """generates the formatted elevenlabs prompt using the tagged phonemes"""
    prompt = ''
    for tag in tags:
        prompt += tag + " "
    return prompt

def gen_EL_prompt(text):
    """goes through full generation suite to create elevenlabs prompt"""
    arpa = to_arpabet(text)
    tagged = phoneme_labelled(arpa)
    prompt = assemble_from_tags(tagged)
    return prompt

def get_phonemes(word: str, normalized_alignment=None):
    """
    Returns ARPAbet phonemes for a word.
    
    Args:
        word (str): The original word (may contain contractions).
        normalized_alignment (dict): Optional mapping of normalized words to phonemes from ElevenLabs.
        
    Returns:
        list[str]: A list of ARPAbet phonemes.
    """
    word_lower = word.lower()

    # Check cache
    if word_lower in phoneme_cache:
        return phoneme_cache[word_lower]

    # Try CMUdict directly
    if word_lower in arpabet:
        phonemes = arpabet[word_lower][0]
        phoneme_cache[word_lower] = phonemes
        return phonemes

    # Expand contractions
    expanded = contractions.fix(word_lower)
    expanded_words = expanded.split()
    phonemes = []
    for w in expanded_words:
        if w in arpabet:
            phonemes += arpabet[w][0]

    if phonemes:
        phoneme_cache[word_lower] = phonemes
        return phonemes

    # Fall back to ElevenLabs normalized alignment
    # normalized_alignment is expected to be a dict: {"word": ["phoneme1", "phoneme2", ...]}
    # UNTESTED DO NOT USE
    # if normalized_alignment and word_lower in normalized_alignment:
    #     phonemes = normalized_alignment[word_lower]
    #     phoneme_cache[word_lower] = phonemes
    #     return phonemes

    # Last resort: just split letters (very naive fallback)
    phonemes = list(word_lower)
    phoneme_cache[word_lower] = phonemes
    return phonemes

def word_alignment_old(text: str, elabs_alignment):
    chars  = elabs_alignment["characters"]
    starts = elabs_alignment["character_start_times_seconds"]
    ends   = elabs_alignment["character_end_times_seconds"]

    word_timings = []

    i = 0
    n = len(chars)
    current_word = ""
    word_start_time = None
    word_end_time = None

    while i < n and i < len(text):
        ch = text[i] if i < len(text) else None
        align_ch = chars[i]

        # Sanity check: alignment and text drifted
        if ch != align_ch:
            # If alignment includes extra spacing, handle gracefully
            # Just skip unmatched alignment chars
            i += 1
            continue

        # If character is whitespace or punctuation:
        if align_ch in string.whitespace or align_ch in string.punctuation:
            # If we have an open word, close it
            if current_word:
                word_timings.append({
                    "word": current_word,
                    "start": word_start_time,
                    "end": word_end_time
                })
                current_word = ""
                word_start_time = None
                word_end_time = None
            i += 1
            continue

        # Regular character — part of a word
        if not current_word:
            word_start_time = starts[i]
        word_end_time = ends[i]
        current_word += align_ch
        i += 1

    # Handle last word if file ends without punctuation
    if current_word:
        word_timings.append({
            "word": current_word,
            "start": word_start_time,
            "end": word_end_time
        })

    return word_timings

def word_alignment(alignment):
    """ Input: JUST THE ALIGNMENT SECTION FROM THE ELEVEN LABS TTS RESPONSE
    converts the characters and their respective alignments to words with 
    summed timings in preperation for conversion to arpabet
    Output Format:
    [
  {'word': 'Hello', 'start': 0.0, 'end': 0.45},
  {'word': '  ', 'start': 0.45, 'end': 0.55},
  {'word': 'world', 'start': 0.6, 'end': 1.1},
  {'word': '!', 'start': 1.1, 'end': 1.2}
]"""
    chars  = alignment["characters"]
    starts = alignment["character_start_times_seconds"]
    ends   = alignment["character_end_times_seconds"]

    word_timings = []

    i = 0
    n = len(chars)
    current_word = ""
    word_start_time = None
    word_end_time = None
    current_is_space = None

    while i < n:
        ch = chars[i]

        is_space = ch in string.whitespace
        is_punct = ch in string.punctuation and ch != "'"

        # initialize state
        if current_word == "":
            current_word = ch
            word_start_time = starts[i]
            word_end_time = ends[i]
            current_is_space = is_space
        else:
            # same category (space or not)? append
            if is_space == current_is_space and not is_punct:
                current_word += ch
                word_end_time = ends[i]
            else:
                # finalize previous token
                word_timings.append({
                    "word": current_word,
                    "start": word_start_time,
                    "end": word_end_time
                })
                # start new token
                current_word = ch
                word_start_time = starts[i]
                word_end_time = ends[i]
                current_is_space = is_space

        i += 1

    # finalize last token
    if current_word:
        word_timings.append({
            "word": current_word,
            "start": word_start_time,
            "end": word_end_time
        })

    return word_timings

def word_alignment_simple(text: str, elabs_alignment):
    chars  = elabs_alignment["characters"]
    starts = elabs_alignment["character_start_times_seconds"]
    ends   = elabs_alignment["character_end_times_seconds"]

    words = text.split()
    word_timings = []
    i = 0  # index into alignment chars

    for word in words:
        word_len = len(word)
        # Skip spaces and punctuation in alignment if they exist
        while i < len(chars) and chars[i].isspace():
            i += 1
        start_time = starts[i]
        end_time = ends[i + word_len - 1]
        word_timings.append({
            "word": word,
            "start": start_time,
            "end": end_time
        })
        i += word_len
        # Skip the space (if any) between words
        while i < len(chars) and chars[i].isspace():
            i += 1
    return word_timings

def to_arpabet(text):
    phonetics = []
    words = text.lower().split()
    for word in words:
        phonetics += arpabet[word][0]
    word_phon_map = [] + words + phonetics
    return word_phon_map

def to_phons(text):
    phonetics_map = to_arpabet(text)
    return phonetics_map[1]


def expand_contractions(text: str) -> str:
    """
    Expands contractions in the given text using the contractions library.
    
    Parameters:
        text (str): Input text containing contractions.
        
    Returns:
        str: Text with contractions expanded.
    """
    expanded_words = []
    
    for word in text.split():
        expanded_words.append(contractions.fix(word))
        
    return " ".join(expanded_words)

def expand_nums(text:str):
    def replace(match):
        num = int(match.group())
        return num2words(num, lang='en_US')  # or 'en_GB'
    
    return re.sub(r'\d+', replace, text)

def word_align_to_arpa(word_alignment):
    arpa_alignment = {'phonemes':[], 'starts':[], 'ends':[]}
    for alignment in word_alignment:
        word = alignment['word'].lower()
        is_punct = all(c in string.punctuation for c in word)
        arpa = [word]
        if not word.isspace() and not is_punct:
            arpa = get_phonemes(word)
            if DEBUG_MODE:
                print(alignment)
                print(arpa)
        start = alignment['start']
        end = alignment['end']
        word_time = end - start
        arpa_timing = word_time/len(arpa)
        # temp_dict = {'phonemes': arpa, 'starts':[], 'ends':[]}
        for phon in arpa:
            arpa_alignment['starts'].append(start)
            start += arpa_timing
            arpa_alignment['ends'].append(start)
            arpa_alignment["phonemes"].append(phon)
    return arpa_alignment

