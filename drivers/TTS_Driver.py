def generate_mock_alignment(text, char_duration=0.15):
    """
    Generate a mock ElevenLabs alignment object for testing.
    
    Parameters:
        text (str): Input text to generate character alignments for.
        char_duration (float): Duration of each character in seconds (default 0.1s).
    
    Returns:
        dict: Alignment object with 'characters', 'character_start_times_seconds',
              'character_end_times_seconds'.
    """
    characters = list(text)
    starts = [i * char_duration for i in range(len(characters))]
    ends = [(i + 1) * char_duration for i in range(len(characters))]

    return {
        "characters": characters,
        "character_start_times_seconds": starts,
        "character_end_times_seconds": ends
    }

