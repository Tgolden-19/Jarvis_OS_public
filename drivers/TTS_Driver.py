def synthesize_audio(text:str):
    """uses piper to synthesize a stream of audio bytes in WAV format"""
    # audio_bytes = voice.synthesize(text, syn_config=syn_config)
    audio_bytes = io.BytesIO()
    with wave.open(audio_bytes, "wb") as wav_file:
        first = True

        for chunk in voice.synthesize(text, syn_config=syn_config):

            # Set WAV header once using the first chunk
            if first:
                wav_file.setnchannels(chunk.sample_channels)
                wav_file.setsampwidth(chunk.sample_width)   # usually 2 bytes
                wav_file.setframerate(chunk.sample_rate)
                first = False

            # Write raw PCM frames into the WAV container
            wav_file.writeframes(chunk.audio_int16_bytes)

    # Return the full WAV file as bytes
    return audio_bytes.getvalue()

